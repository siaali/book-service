package com.siaali.book.task;

import com.siaali.book.mapper.BorrowRecordMapper;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import org.springframework.scheduling.annotation.Scheduled;
import org.springframework.stereotype.Component;

import java.time.LocalDateTime;

/**
 * 逾期检测定时任务。
 *
 * ══════════════════════════════════════════════════════════════
 * 它解决什么问题
 * ══════════════════════════════════════════════════════════════
 * 借书时写入了 due_time（应还时间），但没有任何东西会"自动"发现"这本书过期了"。
 * 数据库不会自己改状态，只能靠一段代码定期去扫一遍，把过期的记录状态改掉。
 * 这段代码就是定时任务（也叫"调度任务""批处理""扫表任务"）。
 *
 * ══════════════════════════════════════════════════════════════
 * 为什么是「定时扫描」而不是「查询时现算」
 * ══════════════════════════════════════════════════════════════
 * 现算的写法：SELECT * FROM borrow_record WHERE status = 0 AND due_time < NOW()
 * 三个问题：
 *   1. 没法给"逾期"这个状态建索引，每次都要做范围扫描（就是上面 5.8 节在优化的那条）
 *   2. 没法统计"本月逾期多少本"这类报表 —— 状态是算出来的，不是存在表里的
 *   3. 没法做事件推送 —— 你不知道"刚刚变成逾期"这个时刻什么时候发生，
 *      因为没人去查，就没有"时刻"
 *
 * 把状态物化（materialize）到字段里，查询、统计、推送都能基于索引做。
 * 代价：需要一个定时任务，且状态可能滞后（最长滞后一个执行周期）。
 *
 * ══════════════════════════════════════════════════════════════
 * 为什么这个类是 @Component 而不是 @Service
 * ══════════════════════════════════════════════════════════════
 * @Component 是"这是个 Spring 管理的普通组件"，
 * @Service 是"这是个业务逻辑组件"，语义更窄。
 * 定时任务是"基础设施性质的调度逻辑"，不是给用户调用的业务服务，
 * 所以用 @Component 更准确。
 *
 * 两个注解都能让 Spring 扫描到并注册成 Bean，功能上没有区别，
 * 区别只在"读代码的人怎么理解这个类的角色"。
 */
@Slf4j
@Component
@RequiredArgsConstructor
public class OverdueTask {

    private final BorrowRecordMapper borrowRecordMapper;

    /**
     * 每天凌晨 3 点执行，把过期的借阅记录标记为逾期。
     *
     * ──────────────────────────────────────────────────────
     * cron 表达式：六位，含义是「秒 分 时 日 月 周」
     * ──────────────────────────────────────────────────────
     *   "0 0 3 * * *"
     *    │ │ │ │ │ └─ 周几：* 表示每天都算
     *    │ │ │ │ └─── 月：* 表示每个月
     *    │ │ │ └───── 日：* 表示每一天
     *    │ │ └─────── 时：3 表示凌晨 3 点（24 小时制）
     *    │ └───────── 分：0 表示第 0 分
     *    └─────────── 秒：0 表示第 0 秒
     *
     * 【为什么是六位，不是五位】
     *   Linux 系统自带的 crontab 是五位（分 时 日 月 周），没有"秒"。
     *   Spring 的 @Scheduled 是六位，第一位是秒。这是最容易搞混的地方 ——
     *   把 Linux 的五位表达式直接抄进来，会变成"每天 3 点 0 分 0 秒"以外的意思，
     *   甚至启动就报错。
     *
     * 【几个常用的写法】
     *   "0 0 3 * * *"      每天凌晨 3:00:00
     *   "0 0 3 * * MON"    每周一凌晨 3:00:00
     *   "0 0 3 1 * *"      每月 1 号凌晨 3:00:00
     *   "0 0/5 * * * *"    每 5 分钟（0/5 表示从 0 开始，每隔 5）
     *   "0 * * * * *"      每分钟的第 0 秒
     *
     * ──────────────────────────────────────────────────────
     * 【为什么用 ${} 占位符，不把时间写死】
     * ──────────────────────────────────────────────────────
     * 写成 @Scheduled(cron = "0 0 3 * * *") 的问题是：
     *   cron 是编译进 class 文件的字符串常量。想改成凌晨 4 点，
     *   必须改代码 → 重新编译 → 重新打包 → 重新部署。
     *   生产环境上，运维半夜发现任务和备份窗口冲突，想调一下时间，
     *   结果要走一次完整的发版流程，这是不合理的。
     *
     * 写成 @Scheduled(cron = "${overdue.cron:0 0 3 * * *}") 之后：
     *   - ${overdue.cron} 是占位符，Spring 启动时会去配置文件/环境变量里找这个键
     *   - 冒号后面的 "0 0 3 * * *" 是「默认值」—— 找不到配置就用它
     *   - 于是调整时间只需要改配置或加环境变量，不用重新编译
     *
     * 这也顺便解决了测试难题：验证时启动加一个环境变量
     *   OVERDUE_CRON="0 * * * * *"
     * 就能让它每分钟跑一次，测完不加这个变量就恢复成凌晨 3 点。
     * 不用改代码、不用改完再改回来，也就不会忘了改回来。
     *
     * 【环境变量名怎么来的】
     *   Spring Boot 的「宽松绑定（relaxed binding）」：
     *   配置键 overdue.cron 对应环境变量 OVERDUE_CRON ——
     *   点号变下划线，全部大写。
     *   同理 server.port 对应 SERVER_PORT。
     */
    @Scheduled(cron = "${overdue.cron:0 0 3 * * *}")
    public void markOverdue() {
        long start = System.currentTimeMillis();

        // LocalDateTime.now() 用服务器本地时区。
        // 【这里有个隐患，面试可以主动提】
        //   如果应用部署在 UTC 时区的容器里，而数据库里的 due_time 是按北京时间写的，
        //   那 now() 会比实际时间早 8 小时，"逾期"的判断就会整体偏移。
        //   严谨的做法是统一用 UTC 存储，展示时再转时区；
        //   或者启动时显式指定 -Duser.timezone=Asia/Shanghai。
        //   本项目是单机本地开发，直接用系统时区，但要知道这个坑存在。
        int count = borrowRecordMapper.markOverdue(LocalDateTime.now());

        long cost = System.currentTimeMillis() - start;

        // 【为什么 count > 0 用 info，count == 0 用 debug】
        //   这个任务每天跑一次，绝大多数时候结果是"没有新增逾期"。
        //   如果两种情况都打 info，日志里每天一行"标记了 0 条"，一年 365 行噪音，
        //   真正需要关注的那一行（标记了 37 条）反而被淹没了。
        //   日志级别的意义就是"区分要不要看"：
        //     info  = 有事发生，需要知道
        //     debug = 正常无事，排查问题时才看
        if (count > 0) {
            log.info("逾期标记完成：本次标记 {} 条，耗时 {} ms", count, cost);
        } else {
            log.debug("逾期标记完成：无新增逾期，耗时 {} ms", cost);
        }
    }
}
